// ---------- гаражи ----------
function garages(b, x, z, n = 6, ry = 0) {
  b.push(M.tr(x, 0, z), M.ry(ry));
  for (let i = 0; i < n; i++) {
    const c = ["#5d6a6e", "#6e5e48", "#4e5a46", "#6a4a40"][i % 4];
    b.box(i * 3.2, 0, 0, 3.1, 2.4, 6, "#4a4844", { mat: "brick" });
    b.box(i * 3.2, 0.05, 3.02, 2.6, 2.1, 0.06, c, { mat: "metal" });
    b.box(i * 3.2, 2.4, 0.3, 3.2, 0.1, 6.6, "#2c2c2c");
  }
  b.pop();
}


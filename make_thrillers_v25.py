def W(loc, cam, actors=(), o=None, **kw):
    """3D-кадр: локация, камера {eye, at, fov, shake}, актёры, опции локации, props/anim/post."""
    w = {"loc": loc, "cam": cam, "actors": list(actors)}
    if o:
        w["o"] = o
    w.update(kw)
    return w


def A(look, **kw):
    return {"look": look, **kw}


def sc(text, world, ui=None, ui_at=None, fx=None, sfx=None):
    d = {"text": text, "world": world, "fx": fx or {"pulse": 100}}
    if ui:
        d["ui"] = ui
        d["uiAt"] = 0.45 if ui_at is None else ui_at
    if sfx:
        d["sfx"] = sfx
    return d


def R(n, big, sub, text, world, pulse=110):
    r = rule(n, big, sub, text, pulse)
    r["world"] = world
    r["uiAt"] = 0
    return r


def note_ui(text, head="ЗАПИСКА"):
    return {"type": "doc", "head": head, "title": "", "text": text, "stamp": False}


